#!/usr/bin/env bash
# TAC-SUNU — one entry point to start, stop and maintain the stack.   ./tac.sh help
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"
# same stack (and database volume) whatever the checkout folder is called
export COMPOSE_PROJECT_NAME="${COMPOSE_PROJECT_NAME:-sunu-tac}"
RUN_DIR="$ROOT/.run"                 # pids + logs of the local (non-Docker) mode
API_URL="http://localhost:8000"
WEB_URL="http://localhost:8080"
LOCAL_WEB_URL="http://localhost:5173"
BACKUP_DIR="$ROOT/backups"           # database dumps (git-ignored)

c_blue=$'\033[1;34m'; c_green=$'\033[1;32m'; c_red=$'\033[1;31m'; c_off=$'\033[0m'
say()  { echo "${c_blue}▸${c_off} $*"; }
ok()   { echo "${c_green}✓${c_off} $*"; }
die()  { echo "${c_red}✗${c_off} $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "$1 is required ($2)"; }

dc()      { docker compose "$@"; }                         # dev: docker-compose.override.yml merged in
dc_prod() { docker compose -f docker-compose.yml "$@"; }   # prod: nginx build, no source mounts

ensure_env() {
  if [[ ! -f .env ]]; then
    cp .env.example .env
    ok ".env created from .env.example — review it (passwords, JWT_SECRET, keys)"
  fi
}

wait_api() {
  say "waiting for the API…"
  for _ in $(seq 1 60); do
    curl -fs "$API_URL/api/meta/config" >/dev/null 2>&1 && { ok "API up"; return 0; }
    sleep 2
  done
  die "API not answering on $API_URL — see: ./tac.sh logs api"
}

urls() {
  echo
  echo "  Test (employees)  $1/"
  echo "  HR console        $1/admin/"
  echo "  API docs          $API_URL/api/docs"
  echo "  Login             admin.drh / ADMIN_PASSWORD (.env)"
}

# ------------------------------------------------------------------------------------------------ Docker

cmd_up() {          # [--build]  dev stack with hot reload (migrations run at API start)
  need docker "Docker Desktop"
  ensure_env
  say "starting db, api, web (dev, hot reload)…"
  dc up -d "$@"
  wait_api
  urls "$WEB_URL"
}

cmd_build() {       # (re)build the dev images, then start
  cmd_up --build
}

cmd_prod() {        # production stack: nginx static build, no source mounts
  need docker "Docker"
  ensure_env
  grep -q '^DEV_PASSWORD=.\+' .env && echo "  ! DEV_PASSWORD is set in .env — empty it in production"
  say "building and starting the production stack…"
  dc_prod up -d --build
  wait_api
  urls "$WEB_URL"
}

cmd_down() {        # stop and remove the containers (data volumes kept)
  dc down
  ok "stack stopped (database volume kept)"
}

cmd_stop() {        # stop everything: Docker stack + local processes
  if command -v docker >/dev/null 2>&1; then dc stop 2>/dev/null || true; fi
  cmd_local_stop quiet
  ok "all TAC processes stopped"
}

cmd_restart() {     # restart api + web (applies new Alembic migrations)
  if [[ $# -eq 0 ]]; then set -- api web; fi
  dc restart "$@"
  wait_api
}

cmd_migrate() {     # apply Alembic migrations (Docker api, or --local)
  if [[ "${1:-}" == "--local" ]]; then
    (cd backend && uv run alembic upgrade head)
  else
    dc exec api uv run --no-dev alembic upgrade head
  fi
  ok "migrations applied"
}

cmd_revision() {    # "message"  create a new autogenerated Alembic migration (local)
  [[ $# -ge 1 ]] || die 'usage: ./tac.sh revision "message"'
  (cd backend && uv run alembic revision --autogenerate -m "$1")
}

cmd_logs() {        # [service…]  follow logs (default: api web)
  if [[ $# -eq 0 ]]; then set -- api web; fi
  dc logs -f --tail=100 "$@"
}

cmd_status() {      # containers, local processes, API health
  dc ps 2>/dev/null || true
  for p in api web; do
    [[ -f "$RUN_DIR/$p.pid" ]] && kill -0 "$(cat "$RUN_DIR/$p.pid")" 2>/dev/null && echo "local $p: running (pid $(cat "$RUN_DIR/$p.pid"))"
  done
  curl -fs "$API_URL/api/meta/config" >/dev/null 2>&1 && ok "API answering on $API_URL" || echo "API not answering on $API_URL"
}

cmd_psql() {        # psql shell on the Docker database
  dc exec db psql -U tac tac
}

cmd_backup() {      # [file]  dump the Docker database (default: backups/tac-<date>.dump)
  mkdir -p "$BACKUP_DIR"
  local f="${1:-$BACKUP_DIR/tac-$(date +%Y%m%d-%H%M%S).dump}"
  dc exec -T db pg_dump -U tac -d tac -Fc >"$f"
  ok "backup written: $f ($(du -h "$f" | cut -f1))"
}

cmd_restore() {     # <file>  replace the Docker database with a dump (asks for confirmation)
  [[ -f "${1:-}" ]] || die "usage: ./tac.sh restore <file.dump>"
  read -r -p "Replace the TAC database with $1? Type 'yes': " a
  [[ "$a" == "yes" ]] || die "aborted"
  dc stop api >/dev/null 2>&1 || true
  dc exec -T db pg_restore -U tac -d tac --clean --if-exists --no-owner <"$1"
  dc start api >/dev/null 2>&1 || true
  ok "restored from $1"
}

cmd_reset_db() {    # DESTROY the Docker database volume and start fresh
  read -r -p "Delete the TAC database volume (all answers)? Type 'yes': " a
  [[ "$a" == "yes" ]] || die "aborted"
  dc down -v
  ok "volumes removed — run ./tac.sh up to recreate"
}

# ------------------------------------------------------------------------------------------------ local (no Docker for the app)

cmd_local() {       # API (uvicorn --reload) + Vite on the host, database = the compose db container (:15433)
  need uv "https://docs.astral.sh/uv/"
  need npm "Node 20+"
  need docker "Docker Desktop"
  ensure_env
  mkdir -p "$RUN_DIR"
  cmd_local_stop quiet
  dc stop api web >/dev/null 2>&1 || true   # same ports as the local processes

  say "starting the TAC database (localhost:15433)…"
  dc up -d --wait db

  say "backend: uv sync + migrations…"
  (cd backend && uv sync -q && uv run alembic upgrade head)
  [[ -d frontend/node_modules ]] || { say "frontend: npm ci…"; (cd frontend && npm ci); }

  say "starting API and Vite in the background (logs in .run/)…"
  (cd backend && nohup uv run uvicorn app.main:app --reload --port 8000 >"$RUN_DIR/api.log" 2>&1 & echo $! >"$RUN_DIR/api.pid")
  (cd frontend && nohup npm run dev >"$RUN_DIR/web.log" 2>&1 & echo $! >"$RUN_DIR/web.pid")
  wait_api
  urls "$LOCAL_WEB_URL"
  echo "  Logs              tail -f .run/api.log .run/web.log      Stop: ./tac.sh local-stop"
}

cmd_local_stop() {  # stop the local api + Vite
  for p in api web; do
    local f="$RUN_DIR/$p.pid"
    if [[ -f "$f" ]]; then
      local pid; pid="$(cat "$f")"
      pkill -P "$pid" 2>/dev/null || true   # children (uvicorn reloader, vite/esbuild)
      kill "$pid" 2>/dev/null || true
      rm -f "$f"
    fi
  done
  [[ "${1:-}" == "quiet" ]] || ok "local processes stopped"
}

# ------------------------------------------------------------------------------------------------ checks

cmd_test() {        # backend pytest + frontend typecheck & vitest
  (cd backend && uv run pytest -q)
  (cd frontend && npm run -s typecheck && npx vitest run)
  ok "all tests passed"
}

cmd_help() {
  cat <<EOF
Usage: ./tac.sh <command> [args]

Docker (recommended)
  up [--build]       start db + api + web in dev mode (hot reload, migrations at start)  → $WEB_URL
  build              rebuild the images, then start (after a dependency / Dockerfile change)
  prod               production stack (nginx build, no source mounts)
  restart [svc…]     restart api + web (applies new migrations)
  stop               stop everything (Docker stack + local processes)
  down               stop and remove the containers (database volume kept)
  logs [svc…]        follow logs (default api web)
  status             containers, local processes, API health
  psql               psql shell on the Docker database
  reset-db           delete the Docker database volume (asks for confirmation)

Database
  migrate [--local]           apply Alembic migrations (in the api container, or on the host)
  revision "message"          new autogenerated migration (host)
  backup [file]               dump the Docker database (default backups/tac-<date>.dump)
  restore <file>              replace the Docker database with a dump (asks for confirmation)

Without Docker for the app
  local              API + Vite on the host, database = the compose db container (:15433) → $LOCAL_WEB_URL
  local-stop         stop them

Checks
  test               backend pytest + frontend typecheck and vitest
EOF
}

cmd="${1:-help}"; shift || true
case "$cmd" in
  up) cmd_up "$@" ;;
  build) cmd_build ;;
  prod) cmd_prod ;;
  down) cmd_down ;;
  stop) cmd_stop ;;
  restart) cmd_restart "$@" ;;
  migrate) cmd_migrate "$@" ;;
  revision) cmd_revision "$@" ;;
  backup) cmd_backup "$@" ;;
  restore) cmd_restore "$@" ;;
  logs) cmd_logs "$@" ;;
  status) cmd_status ;;
  psql) cmd_psql ;;
  reset-db) cmd_reset_db ;;
  local) cmd_local ;;
  local-stop) cmd_local_stop ;;
  test) cmd_test ;;
  help|-h|--help) cmd_help ;;
  *) cmd_help; die "unknown command: $cmd" ;;
esac
