"""Python port of `calcul()` from the legacy TAC-SUNU-test.html, generalised to editable questionnaires.

The server is authoritative: every submission is re-scored here, client scores are ignored.
With the original item bank (default `ref`), results are identical to the JavaScript original — enforced by
tests/test_scoring.py against shared/golden-fixtures.json (generated by running the legacy code itself).
The constants of the original (3 points per situation, 9 blocs per dimension, 5-point scale, 4 twin pairs,
60/40 weights, thresholds) are now read from the questionnaire, and give back the same numbers for it.
"""

from __future__ import annotations

import math
from dataclasses import asdict, dataclass
from typing import Any

from app import questionnaire as Q
from app import referentiel as R


def js_round(x: float) -> int:
    """JavaScript Math.round (half up), not Python's banker's rounding."""
    return math.floor(x + 0.5)


@dataclass
class Result:
    sjt: dict[str, float | None]
    lik: dict[str, float | None]
    scores: dict[str, float | None]
    global_: float | None
    dom: dict[str, float]
    domHaut: str
    domBas: str
    ds: int
    inc: int
    uniforme: bool
    rapide: bool
    dsHaut: bool
    invalide: bool
    dureeS: int | None
    extra: dict[str, float | None] | None = None

    def to_dict(self) -> dict[str, Any]:
        d = asdict(self)
        d["global"] = d.pop("global_")
        return d


def calcul(
    sit: dict[str, int],
    bloc: dict[str, dict[str, int | None]],
    lik: dict[str, int],
    duree_s: int | None,
    ref: dict[str, Any] | None = None,
    extra: dict[str, Any] | None = None,
) -> Result:
    ref = ref or Q.merged_ref(None)
    rules = {**Q.DEFAULT_RULES, **(ref.get("regles") or {})}
    weights = {**Q.DEFAULT_RULES["poids"], **(rules.get("poids") or {})}
    lo, hi = Q.scale_bounds(ref)
    dims = R.dim_keys()
    sjt = {d: {"p": 0, "max": 0} for d in dims}
    lk = {d: {"s": 0, "n": 0} for d in dims}
    ex = {d: {"p": 0.0, "max": 0.0} for d in dims}
    dom = {d: 0 for d in dims}
    dom_n = {d: 0 for d in dims}  # blocs in which each dimension appears

    for q in ref["situations"]:
        sjt[q["dim"]]["max"] += max((o["points"] for o in q["options"]), default=0)
        c = sit.get(q["id"])
        if c is not None and 0 <= c < len(q["options"]):
            sjt[q["dim"]]["p"] += q["options"][c]["points"]

    for b in ref["blocs"]:
        for it in b["items"]:
            dom_n[it["dim"]] += 1
        c = bloc.get(b["id"])
        if not c:
            continue
        most, least = c.get("most"), c.get("least")
        if most is None or least is None or most == least:
            continue
        dom[b["items"][most]["dim"]] += 2
        dom[b["items"][least]["dim"]] -= 1

    for it in ref["likert"]:
        v = lik.get(it["id"])
        if v is None:
            continue
        lk[it["dim"]]["s"] += (lo + hi - v) if it["rev"] else v
        lk[it["dim"]]["n"] += 1

    if extra:
        for e in Q.visible_extras(ref, extra):
            pts = Q.extra_points(e, extra.get(e["id"]))
            if pts is not None and e["dim"] in ex:
                ex[e["dim"]]["p"] += pts[0]
                ex[e["dim"]]["max"] += pts[1]

    validite = ref["validite"]
    # social desirability
    ds = sum(1 for v in validite if v["kind"] == "ds" and lik.get(v["id"]) == hi)
    # consistency between twin items
    inc, inc_n = 0, 0
    for v in validite:
        if v["kind"] != "inc":
            continue
        a, b = lik.get(v["id"]), lik.get(v["pair"])
        if a is None or b is None:
            continue
        bb = (lo + hi - b) if v["opp"] else b
        inc += abs(a - bb)
        inc_n += 1
    norm = rules["incNorm"]
    if inc_n and inc_n < norm:
        inc = js_round(inc * norm / inc_n)
    # uniform pattern
    vals = [lik[it["id"]] for it in ref["likert"] if lik.get(it["id"]) is not None]
    freq: dict[int, int] = {}
    for v in vals:
        freq[v] = freq.get(v, 0) + 1
    uniforme = bool(vals) and len(vals) >= rules["uniformeMin"] and max(freq.values()) / len(vals) > rules["uniformeSeuil"]
    rapide = duree_s is not None and duree_s < rules["rapideS"]
    ds_haut = ds >= rules["dsSeuil"]

    def sjt_pct(d: str) -> float | None:
        return sjt[d]["p"] / sjt[d]["max"] * 100 if sjt[d]["max"] else None

    def lik_pct(d: str) -> float | None:
        n = lk[d]["n"]
        return (lk[d]["s"] - lo * n) / ((hi - lo) * n) * 100 if n else None

    def ex_pct(d: str) -> float | None:
        return ex[d]["p"] / ex[d]["max"] * 100 if ex[d]["max"] else None

    scores: dict[str, float | None] = {}
    for d in dims:
        # weighted mean of the components present (legacy: 0.6 situations + 0.4 practices; situations only
        # when social desirability is high)
        parts = [(weights["sjt"], sjt_pct(d)), (0 if ds_haut else weights["lik"], lik_pct(d)),
                 (weights["extra"], ex_pct(d))]
        parts = [(w, x) for w, x in parts if x is not None and w > 0]
        if not parts:
            scores[d] = None
        elif len(parts) == 1:
            scores[d] = parts[0][1]
        else:
            acc, tw = 0.0, 0.0
            for w, x in parts:
                acc += w * x
                tw += w
            scores[d] = acc if tw == 1 else acc / tw

    ok = [scores[d] for d in dims if scores[d] is not None]
    global_ = None
    if len(ok) == len(dims):
        acc = 0.0
        for x in ok:
            acc += x
        global_ = acc / len(dims)
    dom_pct = {d: (dom[d] + dom_n[d]) / (3 * dom_n[d]) * 100 if dom_n[d] else 50.0 for d in dims}
    srt = sorted(((d, dom_pct[d]) for d in dims), key=lambda t: t[1], reverse=True)

    return Result(
        sjt={d: sjt_pct(d) for d in dims},
        lik={d: lik_pct(d) for d in dims},
        scores=scores,
        global_=global_,
        dom=dom_pct,
        domHaut=srt[0][0],
        domBas=srt[-1][0],
        ds=ds,
        inc=inc,
        uniforme=uniforme,
        rapide=rapide,
        dsHaut=ds_haut,
        invalide=uniforme or inc >= rules["incSeuil"],
        dureeS=duree_s,
        extra={d: ex_pct(d) for d in dims} if any(ex[d]["max"] for d in dims) else None,
    )
